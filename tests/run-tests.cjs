"use strict";
const fs = require("node:fs");
const path = require("node:path");
const vm = require("node:vm");
const assert = require("node:assert/strict");
const { webcrypto } = require("node:crypto");
const html = fs.readFileSync(path.join(__dirname, "..", "perovskite_calculator.html"), "utf8");
const scripts = [...html.matchAll(/<script>([\s\S]*?)<\/script>/g)];
assert.equal(scripts.length, 1, "Expected a single inline application script");
assert(!/<(?:script|link|img|iframe)\b[^>]*\b(?:src|href)\s*=/i.test(html), "External resource dependency found");
assert(!/url\(\s*["']?(?:https?:)?\/\//i.test(html), "Remote CSS dependency found");
assert(!/\b(?:fetch|XMLHttpRequest|WebSocket|EventSource|importScripts)\s*\(/.test(scripts[0][1]), "Network API found");
assert(html.includes("connect-src 'none'"), "Offline connection policy missing");
const context = { crypto: webcrypto };
vm.createContext(context);
vm.runInContext(scripts[0][1], context, { timeout: 10000 });
const tests = context.PerovskiteCalc.selfTests();
for (const test of tests) console.log(`${test.ok ? "PASS" : "FAIL"} ${test.name}${test.error ? ": " + test.error : ""}`);
assert(tests.length >= 21, "Expected all built-in checks");
assert(tests.every(test => test.ok), "Calculation self-tests failed");
console.log(`\n${tests.length}/${tests.length} calculation checks passed; offline resource checks passed.`);
